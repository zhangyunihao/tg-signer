def releases_markdown(current_version: str) -> str:
    """把内置版本记录渲染为 Markdown（最新版本在前，当前版本带标注）。"""
    lines: list[str] = []
    for note in RELEASES:
        title = f"### v{note.version}"
        if note.version == current_version:
            title += "（当前版本）"
        lines.append(title)
        lines.extend(f"- {item}" for item in note.items)
        lines.append("")
    return "\n".join(lines)


def changelog_block(current_version: str) -> None:
    """构建更新日志内容区块，供右上角菜单弹窗使用。"""
    ui.label("更新日志").classes("text-lg font-semibold")
    ui.label(
        f"当前版本 v{current_version} · 最新在前，收录 1.0.54 以来有功能变更的版本"
    ).classes("text-sm text-gray-500")
    with ui.scroll_area().classes("w-full").style("max-height: 62vh"):
        ui.markdown(releases_markdown(current_version)).classes(
            "w-full text-sm tgs-changelog"
        )
